"""Assembles a full incident record from a reconstructed experiment, and the shared
description/summary/postmortem text generation used by both real and synthetic incidents.

Every number that appears in the generated text is read directly from the incident's own
computed fields - nothing here invents a metric value.
"""
from __future__ import annotations

from typing import Optional

from . import config, reconstruct


def compute_deltas(baseline: dict, fault: dict) -> dict:
    """fault - baseline for every (service, metric) pair present in both. Only meaningful where
    both sides have a real (non-null) value - otherwise the delta is omitted rather than
    guessed."""
    deltas: dict[str, dict[str, float]] = {}
    for service, fault_metrics in fault.items():
        baseline_metrics = baseline.get(service, {})
        service_deltas = {}
        for key, fault_value in fault_metrics.items():
            baseline_value = baseline_metrics.get(key)
            if fault_value is not None and baseline_value is not None:
                service_deltas[key] = round(fault_value - baseline_value, 4)
        if service_deltas:
            deltas[service] = service_deltas
    return deltas


def _primary_metric_key(fault_type: str) -> Optional[str]:
    return {
        "memory-leak": "jvm_memory_used_bytes",
        "db-lock": "hikaricp_connections_active",
        "auth-key-error": "http_server_requests_error_count",
        "notification-latency": "http_client_requests_avg_duration_ms",
    }.get(fault_type)


def estimate_severity(fault_type: str, deltas: dict, probe_summary_fault: dict) -> str:
    """A simple, clearly-heuristic severity label - not a ground-truth measurement. Based on the
    magnitude of the fault's primary metric delta on whichever service the metric is actually
    visible on (the *symptom* service - verified against real telemetry, not assumed; e.g.
    auth-key-error's error count is visible on payment-service, not auth-service - see
    config.FAULT_SERVICE_MAP), or (for notification-latency, whose primary signal is caller-side
    duration/success rather than a server-side counter) the probe success rate during the fault
    window."""
    symptom_service = config.FAULT_SERVICE_MAP[fault_type]["symptom_service"]
    key = _primary_metric_key(fault_type)

    if fault_type == "notification-latency":
        rate = probe_summary_fault.get("success_rate")
        if rate is None:
            return "unknown"
        return "high" if rate < 0.5 else ("medium" if rate < 0.95 else "low")

    delta = (deltas.get(symptom_service) or {}).get(key)
    if delta is None:
        return "unknown"

    thresholds = {
        "memory-leak": (20_000_000, 80_000_000),  # bytes
        "db-lock": (3, 7),  # connections
        "auth-key-error": (0.5, 3),  # extra errors observed
    }
    low, high = thresholds.get(fault_type, (0, 0))
    magnitude = abs(delta)
    return "high" if magnitude >= high else ("medium" if magnitude >= low else "low")


def generate_descriptions(incident: dict) -> dict:
    fault_type = incident["fault_type"]
    root = incident["root_cause_service"]
    symptom = incident["symptom_service"]
    probe_fault = incident["payment_probe_summary"]["FAULT_ACTIVE"]
    probe_baseline = incident["payment_probe_summary"]["NORMAL"]
    deltas = incident["metric_deltas"]
    cfg = incident.get("fault_configuration") or {}

    if fault_type == "auth-key-error":
        error_delta = (deltas.get(symptom) or {}).get("http_server_requests_error_count")
        root_cause_description = (
            "auth-service's JWT signing/verification key was replaced with a randomly generated "
            "in-memory key, invalidating tokens issued before the swap. Note: auth-service's own "
            "/api/auth/validate endpoint always returns HTTP 200 (it reports validity in the "
            "response body, not the status code), so this fault is invisible in auth-service's "
            "own error-rate metrics."
        )
        symptom_description = (
            f"Synthetic payment probes reusing a pre-fault token failed with HTTP 401 "
            f"('Invalid or expired token') during the fault window "
            f"(success rate {probe_fault.get('success_rate')}, versus "
            f"{probe_baseline.get('success_rate')} at baseline). The HTTP-level error is "
            f"generated by payment-service's own exception handling in response to the failed "
            f"validation, confirmed by payment-service's http_server_requests_error_count "
            f"rising by {error_delta if error_delta is not None else 'an observed amount'} during "
            f"the fault window - the root cause and the metric-visible symptom are on different "
            f"services."
        )
    elif fault_type == "memory-leak":
        used_delta = (deltas.get(root) or {}).get("jvm_memory_used_bytes")
        root_cause_description = (
            "payment-service's scheduled memory-leak task retained byte[] chunks "
            f"(configured chunk size {cfg.get('chunk_size_bytes', 'n/a')} bytes) without releasing them."
        )
        symptom_description = (
            f"payment-service's JVM heap usage increased by approximately "
            f"{round(used_delta / 1_000_000, 1) if used_delta is not None else 'an unknown amount'} MB "
            "during the fault window relative to baseline, observed directly via jvm_memory_used_bytes."
        )
    elif fault_type == "db-lock":
        active_delta = (deltas.get(root) or {}).get("hikaricp_connections_active")
        held = cfg.get("connectionsHeld", cfg.get("connections_held"))
        root_cause_description = (
            f"ledger-service deliberately acquired and held {held if held is not None else 'several'} "
            "raw JDBC connections from its HikariCP pool without releasing them."
        )
        symptom_description = (
            f"ledger-service's active HikariCP connection count rose by "
            f"{active_delta if active_delta is not None else 'an unknown amount'} during the fault "
            "window, leaving fewer connections available for normal ledger requests."
        )
    else:  # notification-latency
        delay_ms = cfg.get("delayMs", cfg.get("delay_ms", "an increased"))
        root_cause_description = (
            f"notification-service was configured to sleep for {delay_ms}ms before responding to "
            "every receipt request."
        )
        symptom_description = (
            f"payment-service's outbound calls to notification-service, bounded by its own "
            f"~5000ms client-side timeout, resulted in a payment probe success/notification "
            f"success rate of {probe_fault.get('success_rate')} during the fault window "
            f"(avg probe duration {probe_fault.get('avg_duration_ms')}ms vs "
            f"{probe_baseline.get('avg_duration_ms')}ms at baseline) - the symptom appeared on "
            f"payment-service even though the fault was injected on notification-service."
        )

    summary = (
        f"[{fault_type}] Root cause: {root}. Symptom observed on: {symptom}. "
        f"Severity: {incident['severity']}."
    )

    if root != symptom:
        closing_line = (
            f"This incident is used to help future root-cause-analysis retrieval identify "
            f"'{fault_type}' scenarios where the symptom service ({symptom}) differs from the root "
            f"cause service ({root})."
        )
    else:
        closing_line = (
            f"This incident is used to help future root-cause-analysis retrieval identify "
            f"'{fault_type}' scenarios localized to {root}."
        )

    postmortem_text = (
        f"Incident {incident['incident_id']} ({incident['data_source']} data, fault type "
        f"'{fault_type}').\n"
        f"Timeline: NORMAL until {incident['phases']['NORMAL']['end']}, fault injected on "
        f"{root} at {incident['phases']['FAULT_ACTIVE']['start']}, reset at "
        f"{incident['phases']['RECOVERY']['start']}.\n"
        f"Root cause: {root_cause_description}\n"
        f"Symptom: {symptom_description}\n"
        f"Affected services: {', '.join(incident['affected_services'])}.\n"
        f"Errors observed during the fault window: "
        f"{'; '.join(incident['errors_observed']) if incident['errors_observed'] else 'none logged'}.\n"
        f"{closing_line}"
    )

    return {
        "root_cause_description": root_cause_description,
        "symptom_description": symptom_description,
        "summary": summary,
        "postmortem_text": postmortem_text,
    }


def build_incident_from_experiment(
    experiment: dict,
    telemetry: list[dict],
    probes: list[dict],
    incident_id: str,
) -> Optional[dict]:
    """Builds one incident record from one real, live experiment's raw JSONL slice. Returns None
    if the experiment is missing the information needed to build a complete record (e.g. the
    fault injection call itself failed) rather than fabricating placeholder data."""
    if experiment.get("fault_injected_at") is None or experiment.get("fault_reset_at") is None:
        return None

    fault_type = experiment["fault_type"]
    if fault_type not in config.FAULT_SERVICE_MAP:
        return None

    tel_slice, probe_slice = reconstruct.slice_experiment_records(experiment, telemetry, probes)
    labeled_tel = reconstruct.phase_label_telemetry(experiment, tel_slice)
    labeled_probes = reconstruct.phase_label_probes(experiment, probe_slice)

    phases = ["NORMAL", "FAULT_INTRODUCTION", "FAULT_ACTIVE", "RECOVERY"]
    metrics_by_phase = {p: reconstruct.average_metrics_by_service(labeled_tel, p) for p in phases}
    probe_summary_by_phase = {p: reconstruct.summarize_probes(labeled_probes, p) for p in phases}
    errors_by_phase = {p: reconstruct.collect_errors(labeled_tel, labeled_probes, p) for p in phases}

    root = config.FAULT_SERVICE_MAP[fault_type]["root_cause_service"]
    symptom = config.FAULT_SERVICE_MAP[fault_type]["symptom_service"]
    affected = sorted({root, symptom})

    deltas = compute_deltas(metrics_by_phase["NORMAL"], metrics_by_phase["FAULT_ACTIVE"])

    phase_bounds = {
        "NORMAL": {"start": experiment["experiment_start"], "end": experiment["fault_injected_at"]},
        "FAULT_INTRODUCTION": {"start": experiment["fault_injected_at"], "end": experiment["fault_injected_at"]},
        "FAULT_ACTIVE": {"start": experiment["fault_injected_at"], "end": experiment["fault_reset_at"]},
        "RECOVERY": {"start": experiment["fault_reset_at"], "end": experiment["experiment_end"]},
    }

    incident = {
        "incident_id": incident_id,
        "experiment_id": f"{fault_type}-{experiment['experiment_start']}",
        "data_source": "real",
        "generation_method": "live_experiment",
        "fault_type": fault_type,
        "root_cause_service": root,
        "symptom_service": symptom,
        "affected_services": affected,
        "start_time": experiment["experiment_start"],
        "end_time": experiment["experiment_end"],
        "phases": phase_bounds,
        "baseline_metrics": metrics_by_phase["NORMAL"],
        "fault_metrics": metrics_by_phase["FAULT_ACTIVE"],
        "recovery_metrics": metrics_by_phase["RECOVERY"],
        "metric_deltas": deltas,
        "payment_probe_summary": probe_summary_by_phase,
        "errors_observed": errors_by_phase["FAULT_ACTIVE"],
        "correlation_ids": {
            "fault_window_sample": reconstruct.sample_correlation_ids(labeled_tel, labeled_probes, "FAULT_ACTIVE"),
        },
        "fault_configuration": experiment.get("inject_response"),
    }
    incident["severity"] = estimate_severity(fault_type, deltas, probe_summary_by_phase["FAULT_ACTIVE"])
    incident.update(generate_descriptions(incident))
    return incident
